import argparse
import json
import os
from collections import Counter

import numpy as np
from sklearn.metrics import accuracy_score, f1_score, precision_recall_fscore_support
from sklearn.model_selection import GroupShuffleSplit
from transformers import (
    AutoModelForSequenceClassification,
    AutoTokenizer,
    Trainer,
    TrainingArguments,
    set_seed,
)

from config import (
    BATCH_SIZE,
    EPOCHS,
    EVAL_BATCH_SIZE,
    LEARNING_RATE,
    MAX_LENGTH,
    MODEL_NAME,
    OUTPUT_DIR,
    SEED,
    WEIGHT_DECAY,
)
from dataset import MeetingDataset


def parse_args():
    parser = argparse.ArgumentParser(description="Train binary classifier for is_summary_worthy.")
    parser.add_argument(
        "--data-path",
        default="temp/weak_labels_dialogueacts_relabel_v2.jsonl",
        help="Input JSONL generated by weak-label pipeline.",
    )
    parser.add_argument(
        "--label-field",
        default="is_summary_worthy",
        choices=["is_summary_worthy", "has_action_item"],
        help="Target field to train on.",
    )
    parser.add_argument(
        "--text-field",
        default="text",
        help="Text field name in JSONL.",
    )
    parser.add_argument(
        "--group-field",
        default="meeting_id",
        help="Group split field to avoid leakage.",
    )
    parser.add_argument("--val-ratio", type=float, default=0.1)
    parser.add_argument("--output-dir", default=os.path.join(OUTPUT_DIR, "summary_worthy"))
    parser.add_argument("--model-name", default=MODEL_NAME)
    parser.add_argument("--epochs", type=float, default=EPOCHS)
    parser.add_argument("--lr", type=float, default=LEARNING_RATE)
    parser.add_argument("--batch-size", type=int, default=BATCH_SIZE)
    parser.add_argument("--eval-batch-size", type=int, default=EVAL_BATCH_SIZE)
    parser.add_argument("--max-length", type=int, default=MAX_LENGTH)
    parser.add_argument("--seed", type=int, default=SEED)
    parser.add_argument(
        "--max-samples",
        type=int,
        default=0,
        help="If >0, use only first N samples for quick tests.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print split stats only, do not train.",
    )
    return parser.parse_args()


def load_jsonl(path, text_field, label_field, group_field, max_samples=0):
    texts, labels, groups = [], [], []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            obj = json.loads(line)
            text = str(obj.get(text_field, "")).strip()
            if not text:
                continue
            label = int(obj.get(label_field, 0))
            if label not in (0, 1):
                continue
            group = str(obj.get(group_field, obj.get("meeting_id", "unknown")))
            texts.append(text)
            labels.append(label)
            groups.append(group)
            if max_samples > 0 and len(texts) >= max_samples:
                break
    if not texts:
        raise RuntimeError("No samples loaded. Check data path and fields.")
    return texts, labels, groups


def split_by_group(texts, labels, groups, val_ratio, seed):
    idx = np.arange(len(texts))
    splitter = GroupShuffleSplit(n_splits=1, test_size=val_ratio, random_state=seed)
    train_idx, val_idx = next(splitter.split(idx, labels, groups=groups))
    return train_idx.tolist(), val_idx.tolist()


def subset(arr, idx):
    return [arr[i] for i in idx]


def summarize_split(name, labels):
    c = Counter(labels)
    total = len(labels)
    p1 = c.get(1, 0) / total if total else 0
    print(f"{name}: n={total}, y1={c.get(1,0)}, y0={c.get(0,0)}, pos_ratio={p1:.4f}")


def compute_metrics(eval_pred):
    logits, labels = eval_pred
    preds = np.argmax(logits, axis=-1)
    p, r, f1, _ = precision_recall_fscore_support(labels, preds, average="binary", zero_division=0)
    return {
        "accuracy": accuracy_score(labels, preds),
        "precision": p,
        "recall": r,
        "f1": f1,
        "macro_f1": f1_score(labels, preds, average="macro", zero_division=0),
    }


def main():
    args = parse_args()
    set_seed(args.seed)

    texts, labels, groups = load_jsonl(
        args.data_path,
        text_field=args.text_field,
        label_field=args.label_field,
        group_field=args.group_field,
        max_samples=args.max_samples,
    )
    train_idx, val_idx = split_by_group(texts, labels, groups, args.val_ratio, args.seed)

    train_texts, train_labels = subset(texts, train_idx), subset(labels, train_idx)
    val_texts, val_labels = subset(texts, val_idx), subset(labels, val_idx)

    summarize_split("train", train_labels)
    summarize_split("val", val_labels)

    if args.dry_run:
        return

    tokenizer = AutoTokenizer.from_pretrained(args.model_name)
    model = AutoModelForSequenceClassification.from_pretrained(args.model_name, num_labels=2)

    train_dataset = MeetingDataset(train_texts, train_labels, tokenizer, args.max_length)
    val_dataset = MeetingDataset(val_texts, val_labels, tokenizer, args.max_length)

    os.makedirs(args.output_dir, exist_ok=True)
    with open(os.path.join(args.output_dir, "train_config.json"), "w", encoding="utf-8") as f:
        json.dump(vars(args), f, ensure_ascii=False, indent=2)

    training_args = TrainingArguments(
        output_dir=args.output_dir,
        eval_strategy="epoch",
        save_strategy="epoch",
        learning_rate=args.lr,
        per_device_train_batch_size=args.batch_size,
        per_device_eval_batch_size=args.eval_batch_size,
        num_train_epochs=args.epochs,
        weight_decay=WEIGHT_DECAY,
        logging_steps=100,
        load_best_model_at_end=True,
        metric_for_best_model="f1",
        report_to="none",
    )

    trainer = Trainer(
        model=model,
        args=training_args,
        train_dataset=train_dataset,
        eval_dataset=val_dataset,
        compute_metrics=compute_metrics,
    )

    trainer.train()
    trainer.save_model(os.path.join(args.output_dir, "best_model"))
    tokenizer.save_pretrained(os.path.join(args.output_dir, "best_model"))

    with open(os.path.join(args.output_dir, "label_map.json"), "w", encoding="utf-8") as f:
        json.dump({"0": "not_summary_worthy", "1": "summary_worthy"}, f, ensure_ascii=False, indent=2)


if __name__ == "__main__":
    main()
